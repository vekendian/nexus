def is_patched(tree: Path) -> bool:
    """True once any transform has landed.

    The r.smali marker is the normal signal, but a NEXUS_UI=0 build never writes
    it, so the module system's own class is used as the second signal: it is
    copied on every apply, whatever the UI switch says.
    """
    if MARKER in read(tree, "smali/android/ext/r.smali"):
        return True
    return (tree / "smali" / "org" / "vekendian" / "nexus"
            / "ModulePicker.smali").is_file()


def preflight(tree: Path, ids: Ids, profile=None) -> list:
    if profile is None:
        from .profile import Profile
        from .tree import detect_version
        profile = Profile.for_release(detect_version(tree))
    if profile is None:
        from .profile import Profile
        profile = Profile.for_release(detect_version(Path(".")))
    errors = []
    main = read(tree, "res/layout/main.xml")
    public = read(tree, "res/values/public.xml")
    smali = read(tree, "smali/android/ext/r.smali")
    styles = read(tree, "res/values/styles.xml")
    nexus_styles = (tree / "res/values/nexus_styles.xml")
    nexus_styles = nexus_styles.read_text(encoding="utf-8") if nexus_styles.is_file() else ""

    # --- resource-id space -------------------------------------------------
    # Run against the SOURCE tree, before a single line is written. These three
    # replace the old public.xml-only collision audit: pins must be checked
    # against the whole id space of the release actually being patched, not
    # against the numbers recorded for whichever release nexus_ids.json was last
    # touched for.
    errors.extend(audit_collisions(tree, ids.pinned_table()))
    errors.extend(audit_pin_ceiling(tree, ids.pinned_table()))
    # Every GG view Nexus binds to must still exist under the same name. The
    # ids are resolved by name at apply time, so a renamed view used to fail
    # there -- after the copy, after the preflight had already said "fine".
    errors.extend(ids.audit_gg_bindings())

    if MARKER in smali:
        errors.append("already patched (marker %r in r.smali) — point --src at the original, unpatched tree" % MARKER)

    for cid in CONTRACT_IDS:
        if f'<public type="id" name="{cid}"' not in public:
            errors.append(f"contract id missing from public.xml: {cid}")

    errors.extend(ids.audit_collisions(public))
    _ns_path = RES_DIR / "res/values/nexus_strings.xml"
    _nexus_strings = _ns_path.read_text(encoding="utf-8") if _ns_path.is_file() else ""
    for _kind, _name, _hexval in ids.pinned_table():
        if _kind == "string" and _name not in _nexus_strings:
            errors.append(f"nexus_strings.xml: missing definition for {_name}")

    # The module engine ships as generated smali plus one dex asset. Both are
    # produced by build-engine.sh; their absence means the committed build is
    # stale, which would otherwise show up as an empty EXTENSIONS tab on device.
    for _rel in ENGINE_SMALI:
        if not (RES_DIR / _rel).is_file():
            errors.append(f"engine class missing (run build-engine.sh): {_rel}")
    _asset = RES_DIR / ENGINE_ASSET
    if not _asset.is_file():
        errors.append(f"engine asset missing (run build-engine.sh): {ENGINE_ASSET}")
    elif not _asset.read_bytes()[:4] == b"dex\n":
        errors.append(f"{ENGINE_ASSET} is not a dex file")

    # Lua namespace: templates are rendered against the lock file at apply time,
    # so every placeholder must resolve, and the single GG-owned edit (the
    # registration call in Script.call) must have its anchor exactly where
    # luapatch expects it.
    if not lua_templates():
        errors.append("lua templates missing: resources/smali_lua")
    for _rel, _tokens in template_tokens().items():
        for _token in _tokens:
            try:
                ids.hex(_token)
            except PatchError:
                errors.append(f"lua template {_rel}: unknown id placeholder {_token}")
    _script_p = tree / LUA_SCRIPT_REL
    if not _script_p.is_file():
        errors.append(f"Script.smali missing: {LUA_SCRIPT_REL}")
    else:
        _script = _script_p.read_text(encoding="utf-8")
        if SCRIPT_HELPER_MARK in _script:
            errors.append("Script.smali: nexusInstall already present (already patched?)")
        _n = anchor_count(_script, LUA_SCRIPT_ANCHOR)
        if _n != 1:
            errors.append(f"Script.smali: nexus registration anchor found "
                          f"{_n}x (expected 1x)")
        _n = anchor_count(_script, W3_ENTRY_ANCHOR)
        if _n != 1:
            errors.append(f"Script.smali: W3 entry anchor found {_n}x "
                          f"(expected 1x)")

    # Execute script dialog: the "?" action is replaced with the static help
    # dialog. The case block must still look the way luapatch expects, and the
    # GG text-dialog helper it calls must still exist (apicheck only resolves
    # framework calls, not obfuscated GG classes).
    try:
        _help_id = ids.hex("nexus_str_lua_help")
    except PatchError:
        _help_id = None
        errors.append("id lock: nexus_str_lua_help is not pinned")
    _help_p = tree / LUA_HELP_REL
    if not _help_p.is_file():
        errors.append(f"Execute-script dialog missing: {LUA_HELP_REL}")
    else:
        _help = _help_p.read_text(encoding="utf-8")
        if _help_id and _help_id in _help:
            errors.append("o0$b.smali: Lua help dialog already present "
                          "(already patched?)")
        _n = anchor_count(_help, LUA_HELP_ANCHOR)
        if _n != 1:
            errors.append(f"o0$b.smali: examples anchor found {_n}x (expected 1x)")
    _tools_p = tree / "smali/android/ext/Tools.smali"
    if not _tools_p.is_file():
        errors.append("Tools.smali missing: the help dialog helper is unreachable")
    elif ".method public static h(Ljava/lang/String;I)V" not in \
            _tools_p.read_text(encoding="utf-8"):
        errors.append("Tools.smali: text-dialog helper h(String,int) is gone")

    for _rel in ["res/values/nexus_strings.xml", "res/values/nexus_styles.xml",
                 "res/layout/nexus_extension_card.xml",
                 "res/drawable/nexus_bg_fab.xml",
                 "res/drawable/nexus_bg_float_badge.xml",
                 "res/drawable/nexus_bg_float_button.xml",
                 "res/drawable/nexus_ic_plus.xml",
                 "res/drawable/nexus_ic_close.xml",
                 "res/drawable/nexus_bg_dialog.xml", "res/drawable/nexus_bg_button.xml",
                 "res/drawable/nexus_bg_button_bar.xml",
                 "res/drawable/nexus_kbd_key_pressed.xml"]:
        if not (RES_DIR / _rel).is_file():
            errors.append(f"patcher resource missing: {_rel}")

    # Empty states: the two wirings transform_empty_views must cut (exact
    # shape, one per view id), and the pairs of views in service_dialog.xml
    # the transform marks gone and the startup scramble keeps alive.
    _ms = tree / "smali/android/ext/MainService.smali"
    if not _ms.is_file():
        errors.append("MainService.smali missing: empty-state wiring unknowable")
    else:
        _mst = _ms.read_text(encoding="utf-8")
        for _nm in ("nothing_found_view", "empty_list_view"):
            try:
                _hex = ids.gg(_nm)
            except PatchError:
                errors.append(f"public.xml: id {_nm} not resolvable by name")
                continue
            _n = len(set_empty_view_pattern(_hex).findall(_mst))
            if _n != 1:
                errors.append(f"MainService.smali: {_nm} setEmptyView wiring "
                              f"found {_n}x (expected 1x)")
    _sd = tree / "res/layout/service_dialog.xml"
    if not _sd.is_file():
        errors.append("service_dialog.xml missing: empty-state views unknowable")
    else:
        _sdx = _sd.read_text(encoding="utf-8")
        for _nm in ("nothing_found_view", "empty_list_view"):
            _m = re.search(rf"<[^>]*android:id=\"@id/{_nm}\"[^>]*>", _sdx)
            if _m is None:
                errors.append(f"service_dialog.xml: {_nm} not found")
            elif 'android:visibility' in _m.group(0):
                errors.append(f"service_dialog.xml: {_nm} already carries a "
                              f"visibility attr (already patched?)")
        for _nm in ("nothing_found_text", "empty_list_text"):
            if f'android:id="@id/{_nm}"' not in _sdx:
                errors.append(f"service_dialog.xml: {_nm} missing — the startup "
                              f"scramble reads its text and would crash")
        # Stock states the list transform keys on: addr_list must ship gone
        # (it is the anchor the visible rewrite replaces), saved_list must
        # ship attribute-free (the visible attr is appended to it).
        _al = re.search(r'<[^>]*android:id="@id/addr_list"[^>]*>', _sdx)
        if _al is None:
            errors.append("service_dialog.xml: addr_list not found")
        elif 'android:visibility="gone"' not in _al.group(0):
            errors.append("service_dialog.xml: addr_list is not stock-gone — "
                          "the lists-visible rewrite keys on the stock table")
        _sl = re.search(r'<[^>]*android:id="@id/saved_list"[^>]*>', _sdx)
        if _sl is None:
            errors.append("service_dialog.xml: saved_list not found")
        elif 'android:visibility' in _sl.group(0):
            errors.append("service_dialog.xml: saved_list already carries a "
                          "visibility attr (already patched?)")

    # Searcher spacing: the transform keys on this file's stock structure —
    # one root ScrollView carrying the two 6dip side insets, the two grid
    # buttons and the id-less rows keyed from the anchors below.
    _ss = tree / "res/layout/service_searcher.xml"
    if not _ss.is_file():
        errors.append("service_searcher.xml missing: searcher spacing "
                      "unknowable")
    else:
        _ssx = _ss.read_text(encoding="utf-8")
        if _ssx.count("<android.fix.ScrollView") != 1:
            errors.append("service_searcher.xml: root ScrollView shape changed")
        for _pad in SEARCHER_STOCK_PADS:
            if _pad not in _ssx:
                errors.append(f"service_searcher.xml: stock inset {_pad} "
                              "missing — the root insets moved")
        for _vid in ("@id/fuzzy_row", "@id/equal_btn", "@id/not_equal_btn",
                     "@id/larger_btn", "@id/smaller_btn", "@id/memory_range"):
            if f'android:id="{_vid}"' not in _ssx:
                errors.append(f"service_searcher.xml: {_vid} missing")
        for _anchor in ('android:text="@string/limit"',
                        'android:id="@id/cancel"'):
            if _anchor not in _ssx or _ssx.count(_anchor) != 1:
                errors.append(f"service_searcher.xml: row anchor {_anchor} "
                              "not found exactly once")

    # Floating interface. The float is a system overlay over a game screen, so
    # it is restyled in GG's own layouts: both files must still carry the
    # elements and the purple badge the transforms key on.
    for _nm in ("nexus_str_float_icon", "nexus_str_float_speed_dec",
                "nexus_str_float_speed_inc", "nexus_str_float_time_jump",
                "nexus_str_float_time_jump_last"):
        if f'name="{_nm}"' not in _nexus_strings:
            errors.append(f"nexus_strings.xml: missing definition for {_nm}")
    _hp = tree / "res/layout/hot_point_view.xml"
    if not _hp.is_file():
        errors.append("hot_point_view.xml missing")
    else:
        _hpx = _hp.read_text(encoding="utf-8")
        for _what, _blob in (("icon", 'android:id="@id/hot_point_icon"'),
                             ("frame", 'android:id="@id/hot_frame"'),
                             ("speed_dec", 'android:id="@id/speed_dec"'),
                             ("speed_inc", 'android:id="@id/speed_inc"'),
                             ("readout", 'android:id="@id/progress_bar_text"'),
                             ("readout container", 'android:id="@id/progress_layout"'),
                             ("progress bar", 'android:id="@id/progress_bar"'),
                             ("stage bar", 'android:id="@id/progress_bar_stage"'),
                             ("speed badge", 'android:id="@id/speed_text"')):
            if _blob not in _hpx:
                errors.append(f"hot_point_view.xml: {_what} not found")
        if 'android:background="#80000000"' not in _hpx:
            errors.append("hot_point_view.xml: readout scrim anchor not found")
        if 'android:background="@drawable/txt_bg"' not in _hpx:
            errors.append("hot_point_view.xml: speed badge anchor not found")
    _tj = tree / "res/layout/time_jump_panel.xml"
    if not _tj.is_file():
        errors.append("time_jump_panel.xml missing")
    else:
        _tjx = _tj.read_text(encoding="utf-8")
        for _what, _blob in (("time_jump", 'android:id="@id/time_jump"'),
                             ("time_jump_last", 'android:id="@id/time_jump_last"')):
            if _blob not in _tjx:
                errors.append(f"time_jump_panel.xml: {_what} not found")
        # The panel's root tag, word-bounded: "<android.ext.TimeJumpPanelX"
        # would satisfy a plain prefix test and then fail in the transform.
        if not re.search(r"<android\.ext\.TimeJumpPanel\b", _tjx):
            errors.append("time_jump_panel.xml: panel root not found")
        if 'android:background="@drawable/txt_bg"' not in _tjx:
            errors.append("time_jump_panel.xml: panel background anchor not found")

    # download-URL anchors
    for _rel in ("smali/android/ext/r$n.smali", "smali/android/ext/ShowApp.smali",
                 "smali/android/ext/MainService$m.smali"):
        _p = tree / _rel
        if not _p.is_file():
            errors.append(f"url anchor file missing: {_rel}")
        elif DOWNLOAD_URL_OLD not in _p.read_text(encoding="utf-8"):
            errors.append(f"url anchor missing in {_rel}")
    if smali.count('"' + DOWNLOAD_URL_OLD + '"') != 0:
        errors.append("r.smali: download-URL literal unexpectedly bare")
    if smali.count('"#' + DOWNLOAD_URL_OLD + '"') != 1:
        errors.append("r.smali: commented download-URL literal not found")

    # keyboard anchors
    if anchor_count(read(tree, "res/layout/keyboard.xml"), KBD_LAYOUT_ANCHOR) != 1:
        errors.append("keyboard.xml: background anchor not found")
    if anchor_count(read(tree, "res/layout/keyboard.xml"),
                    KBD_GRAVITY_ANCHOR) != 1:
        errors.append("keyboard.xml: HorizontalScrollView centering anchor "
                      "not found")
    _ks = read(tree, "res/drawable/btn_keyboard_key_lxx_dark.xml")
    if "<selector" not in _ks or "</selector>" not in _ks:
        errors.append("btn_keyboard_key_lxx_dark.xml: <selector> not found")

    # settings screen: donate row to delete, purple bands to recolour
    _sc = tree / "res/layout/service_config.xml"
    if not _sc.is_file():
        errors.append("service_config.xml missing")
    else:
        _scx = _sc.read_text(encoding="utf-8")
        _n = len(DONATE_ROW_RE.findall(_scx))
        if _n != 1:
            errors.append(f"service_config: donate row found {_n}x (expected 1x)")
        if anchor_count(_scx, SERVICE_SEPARATOR_BG) != SERVICE_SEPARATOR_COUNT:
            errors.append(
                f"service_config: separator bands found "
                f"{anchor_count(_scx, SERVICE_SEPARATOR_BG)}x "
                f"(expected {SERVICE_SEPARATOR_COUNT}x)")
        if len(GAME_SECTION_ROW_RE.findall(_scx)) != 1:
            errors.append(
                "service_config: game_section row not found exactly once")
    _ca = tree / CONFIG_ADAPTER
    if not _ca.is_file():
        errors.append(f"settings highlight: {CONFIG_ADAPTER} missing")
    elif anchor_count(_ca.read_text(encoding="utf-8"),
                      SETTINGS_HIGHLIGHT_ANCHOR) != 1:
        errors.append("settings highlight: yellow const anchor not found")

    for what, blob, cnt in [
        ("front_text block", FRONT_TEXT_BLOCK, 1),
        ("button rows (visibility targets)", ROW_OPEN, 2),
        ("ScrollView open", "        <android.fix.ScrollView", 1),
        ("ScrollView close", "        </android.fix.ScrollView>", 1),
        ("start-button/navbar insert point", START_ANCHOR, 1),
    ]:
        got = anchor_count(main, blob)
        if got != cnt:
            errors.append(f"main.xml anchor {what!r} found {got}x (expected {cnt}x)")

    for what, blob in [
        ("y(Z)V button-count const", COUNT_ANCHOR),
        (":array_0 payload", ARRAY_ANCHOR),
        ("onClick sparse-switch block", SWITCH_ANCHOR),
    ]:
        if anchor_count(smali, blob) != 1:
            errors.append(f"r.smali anchor {what!r} found {anchor_count(smali, blob)}x (expected 1x)")

    if not ONCLICK_METHOD_RE.search(smali):
        errors.append("r.smali: onClick(Landroid/view/View;)V not found")

    if anchor_count(styles, STYLES_ANCHOR) != 1:
        errors.append(f"styles.xml anchor found {anchor_count(styles, STYLES_ANCHOR)}x (expected 1x)")

    if not (RES_DIR / "res").is_dir():
        errors.append(f"resources missing: {RES_DIR / 'res'}")

    for rel in icon_resource_files():
        if not (RES_DIR / rel).is_file():
            errors.append(f"icon override missing: {RES_DIR / rel}")

    # rebrand anchors. The package comes from the tree: GG randomizes it per
    # build, so there is no literal to compare against.
    manifest = read(tree, "AndroidManifest.xml")
    try:
        old_pkg = detect_package(tree)
    except PatchError as e:
        old_pkg = None
        errors.append(f"rebrand: {e}")
    if old_pkg is not None:
        old_path = old_pkg.replace(".", "/")
        if not (tree / "smali" / old_path).is_dir():
            errors.append(
                f"rebrand: smali/{old_path} missing (already rebranded?)")
        if f'package="{old_pkg}"' not in manifest:
            errors.append(f"rebrand: manifest package is not {old_pkg}")
    if SMALI_NEW in read(tree, "smali/android/ext/r.smali"):
        errors.append("rebrand: Lorg/vekendian/nexus/ already present (already rebranded?)")
    if not re.search(r"<application\b[^>]*android:label=", manifest, re.DOTALL):
        errors.append("rebrand: application android:label not found in manifest")
    if manifest.count('android:label="Game"') != 2:
        errors.append('rebrand: expected 2 activity android:label="Game"')
    # Located by attribute, not indentation: MT Manager pretty-prints one
    # attribute per line while apktool collapses them onto the element's line.
    hw = re.search(r'<activity\b[^>]*?android:icon="@mipmap/ic_hw_48dp"[^>]*?>', manifest)
    if not hw or "ActivityMain" not in hw.group(0):
        errors.append("rebrand: ActivityMain HW launcher block not found")
    if manifest.count('android.intent.category.LEANBACK_LAUNCHER') != 2:
        errors.append("rebrand: expected 2 LEANBACK_LAUNCHER categories in clean manifest")
    if manifest.count('android.intent.category.LAUNCHER') != 2:
        errors.append("rebrand: expected 2 LAUNCHER categories in clean manifest")
    strings = tree / "res/values/strings.xml"
    if strings.is_file() and APP_NAME_OLD not in strings.read_text(encoding="utf-8"):
        errors.append("rebrand: strings.xml app_name is not GameGuardian")
    if strings.is_file():
        _s = strings.read_text(encoding="utf-8")
        # The user-visible version lives here, not in the manifest: the
        # About screen and the float's status line read this element. The
        # rewrite keys on the element, so only its presence is pinned —
        # the value is release-specific.
        if len(re.findall(r'<string name="version_number">[^<]*</string>', _s)) != 1:
            errors.append("rebrand: strings.xml version_number entry not "
                          "found exactly once — the display version is not "
                          "rewritable")
    return errors


def delta_audits_skipped(src: Path | None) -> bool:
    """True when the two delta audits could not run.

    They need the unpatched tree to diff against. Reporting this as a warning
    rather than an error keeps `check` honest about what it did and did not
    verify, without failing a tree that is otherwise fine.
    """
    return src is None or not src.is_dir()


def audit_raw_asset_names(tree: Path) -> list:
    """Every res/raw/ file must be named ydw*.

    MainService.Z() walks the APK's zip entries and computes a divisor from
    their names; an entry under res/raw/ whose name does not contain
    "res/raw/ydw" makes that divisor zero. The resulting ArithmeticException is
    swallowed by Z()'s catchall, G is bound to addr_item_type (which is not in
    service_dialog), and Z0 dereferences the null ListView. Every raw resource
    GameGuardian ships is named ydw*, so the prefix is the invariant, not a
    coincidence. This check exists so the next added asset cannot reintroduce
    the crash silently.
    """
    out = []
    raw = tree / "res" / "raw"
    if not raw.is_dir():
        return out
    for entry in sorted(raw.iterdir()):
        if entry.is_file() and not entry.name.startswith("ydw"):
            out.append(f"res/raw/{entry.name}: name must start with 'ydw' or "
                       f"MainService.Z() divides by zero (see audit_raw_asset_names)")
    return out


