#!/usr/bin/env python3
"""Regenerate tests/fixtures/mini_r.smali from the live anchor constants.

Deriving the fixture from the anchors keeps the two from drifting, and means a
test can assert the full transform runs without shipping a GameGuardian tree.
Run after changing any anchor:  python3 tests/make_fixture.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from nexus import modules, smali  # noqa: E402

TEMPLATE = '''# Mini r.smali fixture -- GENERATED by tests/make_fixture.py, do not hand-edit.
#
# Embeds every anchor in nexus/smali.py verbatim so anchors.py, ids.py and
# transform_smali() can be exercised with no GameGuardian tree on disk.
# Not a runnable class.

.class public Landroid/ext/r;
.super Landroid/app/Activity;

.method public onClick(Landroid/view/View;)V
{registers}
{count}
{array}
{switch}
.end method

.method protected onActivityResult(IILandroid/content/Intent;)V
{aar_head}
    new-instance v0, Landroid/lang/StringBuilder;

    invoke-direct {{v0}}, Landroid/lang/StringBuilder;-><init>()V

    iget-boolean v1, p0, Landroid/ext/r;->d:Z

    if-eqz v1, :cond_0

    const-string v1, "Installer: "

    goto :goto_0

    :cond_0
    const-string v1, ""

    :goto_0
    invoke-virtual {{v0, v1}}, Landroid/lang/StringBuilder;->append(Ljava/lang/String;)Ljava/lang/StringBuilder;

    const-string v1, "onActivityResult()"

    invoke-virtual {{v0, v1}}, Landroid/lang/StringBuilder;->append(Ljava/lang/String;)Ljava/lang/StringBuilder;

    invoke-virtual {{v0}}, Landroid/lang/StringBuilder;->toString()Ljava/lang/String;

    move-result-object v0

    invoke-static {{v0}}, Landroid/ext/e1;->d(Ljava/lang/String;)I

    invoke-super {{p0, p1, p2, p3}}, Landroid/app/Activity;->onActivityResult(IILandroid/content/Intent;)V

    iget-boolean v0, p0, Landroid/ext/r;->d:Z

    if-eqz v0, :cond_1

    invoke-static {{p1, p2, p3}}, Landroid/ext/b1;->F0(IILandroid/content/Intent;)V

    goto :goto_1

    :cond_1
    invoke-static {{}}, Landroid/ext/s1;->u()Z

    move-result p1

    if-eqz p1, :cond_2

    invoke-static {{}}, Landroid/ext/s1;->A()V

    goto :goto_1

    :cond_2
    invoke-static {{}}, Landroid/ext/z;->m()V

    :goto_1
    return-void
.end method

.method protected onSaveInstanceState(Landroid/os/Bundle;)V
{on_pause}
{resume}
{postresume}
{z}
{power}
.end method
'''


def main() -> int:
    out = TEMPLATE.format(
        registers=smali.REGISTERS_ANCHOR,
        count=smali.COUNT_ANCHOR,
        array=smali.ARRAY_ANCHOR,
        switch=smali.SWITCH_ANCHOR,
        on_pause=smali.ON_PAUSE_ANCHOR,
        resume=smali.RESUME_ANCHOR,
        postresume=smali.POSTRESUME_ANCHOR,
        z=smali.Z_ANCHOR,
        power=smali.POWER_METHODS_NEW_RAW.split("@@NEXUS_APPLY_TAB@@")[0].rstrip(),
        aar_head=modules.ONACTIVITYRESULT_ANCHOR,
    )
    dest = Path(__file__).resolve().parent / "fixtures" / "mini_r.smali"
    dest.write_text(out, encoding="utf-8")

    bad = []
    for name in ("REGISTERS_ANCHOR", "COUNT_ANCHOR", "ARRAY_ANCHOR", "SWITCH_ANCHOR",
                 "ON_PAUSE_ANCHOR", "RESUME_ANCHOR", "POSTRESUME_ANCHOR",
                 "Z_ANCHOR", "POWER_METHODS_ANCHOR"):
        n = out.count(getattr(smali, name))
        if n != 1:
            bad.append(f"{name}: {n}x")
    if out.count(modules.ONACTIVITYRESULT_ANCHOR) != 1:
        bad.append("ONACTIVITYRESULT_ANCHOR: %dx"
                   % out.count(modules.ONACTIVITYRESULT_ANCHOR))
    print(f"wrote {dest} ({len(out)} chars)")
    if bad:
        print("ANCHOR NOT MATCHED EXACTLY ONCE:")
        for b in bad:
            print(f"  - {b}")
        return 1
    print("all anchors present exactly once")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
